#!/usr/bin/env python3
"""
Build + upload + publish OTA release automatically.

Flow:
1) Detect version automatically (VERSION file -> prj.conf FW_REV_STR -> git tag)
2) Build release image (optional)
3) Compute SHA256 and size for zephyr.signed.bin
4) Create release via backend API (receives upload_url)
5) Upload binary to cloud storage (presigned URL PUT)
6) Publish release in backend
7) Write local release manifest

Usage:
  python tools/publish_ota_release.py \
    --api-base-url https://<api-id>.execute-api.<region>.amazonaws.com \
    --admin-token <admin-token> \
    --channel stable \
    --board arduino_nano_33_ble \
    --sysbuild --pristine
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional
from urllib import error, request

SEMVER_RE = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)(?:[-+][0-9A-Za-z.-]+)?$")


def normalize_base_url(base_url: str) -> str:
    url = base_url.strip().rstrip("/")
    if not (url.startswith("http://") or url.startswith("https://")):
        raise ValueError("--api-base-url must start with http:// or https://")
    return url


def run_command(cmd: list[str], cwd: Path) -> None:
    print("[RUN] " + " ".join(cmd))
    env = os.environ.copy()
    python_exe = sys.executable
    env["WEST_PYTHON"] = python_exe
    env["PYTHON_EXECUTABLE"] = python_exe
    result = subprocess.run(cmd, cwd=str(cwd), text=True, env=env)
    if result.returncode != 0:
        raise RuntimeError(f"Command failed ({result.returncode}): {' '.join(cmd)}")


def resolve_west_cmd() -> list[str]:
    west_exe = shutil.which("west")
    if west_exe:
        return [west_exe]
    return [sys.executable, "-m", "west"]


def semver_normalize(version: str) -> str:
    match = SEMVER_RE.match(version.strip())
    if not match:
        raise ValueError(f"Invalid semantic version: {version!r}")
    return f"{int(match.group(1))}.{int(match.group(2))}.{int(match.group(3))}"


def get_version_from_version_file(project_root: Path) -> Optional[str]:
    version_file = project_root / "VERSION"
    if not version_file.exists():
        return None
    raw = version_file.read_text(encoding="utf-8").strip()
    if not raw:
        return None

    lines = [line.strip() for line in raw.splitlines() if line.strip() and not line.strip().startswith("#")]
    if len(lines) == 1 and "=" not in lines[0]:
        return semver_normalize(lines[0])

    values: Dict[str, str] = {}
    for line in lines:
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"')

    major = values.get("VERSION_MAJOR", "")
    minor = values.get("VERSION_MINOR", "")
    patch = values.get("PATCHLEVEL", "")
    if major.isdigit() and minor.isdigit() and patch.isdigit():
        return f"{int(major)}.{int(minor)}.{int(patch)}"

    return None


def get_version_from_prj_conf(project_root: Path) -> Optional[str]:
    prj_conf = project_root / "prj.conf"
    if not prj_conf.exists():
        return None

    for line in prj_conf.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("CONFIG_BT_DIS_FW_REV_STR="):
            value = line.split("=", 1)[1].strip().strip('"')
            if value:
                return semver_normalize(value)
    return None


def get_version_from_git_tag(project_root: Path) -> Optional[str]:
    result = subprocess.run(
        ["git", "describe", "--tags", "--abbrev=0"],
        cwd=str(project_root),
        text=True,
        capture_output=True,
    )
    if result.returncode != 0:
        return None
    tag = result.stdout.strip()
    if not tag:
        return None
    return semver_normalize(tag)


def detect_version(project_root: Path, explicit_version: str) -> str:
    if explicit_version.strip():
        return semver_normalize(explicit_version)

    for resolver in (get_version_from_version_file, get_version_from_prj_conf, get_version_from_git_tag):
        detected = resolver(project_root)
        if detected:
            return detected

    raise RuntimeError(
        "Unable to detect version automatically. Provide --version or create a VERSION file."
    )


def write_release_version_conf(project_root: Path, version: str) -> Path:
    conf_path = project_root / "build" / "ota_release_version.conf"
    conf_text = "\n".join(
        [
            "# Auto-generated by publish_ota_release.py",
            f'CONFIG_BT_DIS_FW_REV_STR="{version}"',
            "",
        ]
    )
    conf_path.parent.mkdir(parents=True, exist_ok=True)
    conf_path.write_text(conf_text, encoding="utf-8")
    return conf_path


def build_release(
    project_root: Path,
    build_dir: Path,
    board: str,
    sysbuild_enabled: bool,
    pristine: bool,
    extra_conf_file: Path,
) -> None:
    cmd = resolve_west_cmd() + ["build", "-b", board, "-d", str(build_dir)]
    if sysbuild_enabled:
        cmd.append("--sysbuild")
    if pristine:
        cmd.append("--pristine")

    if sysbuild_enabled:
        conf_arg = str(extra_conf_file)
        cmd.extend(
            [
                "--",
                f"-DAutoWatering_EXTRA_CONF_FILE={conf_arg}",
                f"-Dapp_EXTRA_CONF_FILE={conf_arg}",
            ]
        )
    else:
        cmd.extend(["--", f"-DEXTRA_CONF_FILE={extra_conf_file}"])

    run_command(cmd, project_root)


def find_signed_bin(build_dir: Path) -> Path:
    candidates = [
        build_dir / "AutoWatering" / "zephyr" / "zephyr.signed.bin",
        build_dir / "zephyr" / "zephyr.signed.bin",
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise RuntimeError(f"Signed binary not found in: {', '.join(str(p) for p in candidates)}")


def sha256_of_file(file_path: Path) -> str:
    digest = hashlib.sha256()
    with file_path.open("rb") as file_handle:
        for chunk in iter(lambda: file_handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def api_json_request(url: str, method: str, headers: Dict[str, str], payload: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    data = None
    req_headers = dict(headers)
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        req_headers["Content-Type"] = "application/json"

    req = request.Request(url, data=data, method=method, headers=req_headers)
    try:
        with request.urlopen(req, timeout=30) as resp:
            raw = resp.read().decode("utf-8")
            return json.loads(raw) if raw else {}
    except error.HTTPError as exc:
        details = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"API {method} {url} failed: HTTP {exc.code}: {details}") from exc
    except error.URLError as exc:
        raise RuntimeError(f"API {method} {url} request failed: {exc}") from exc


def upload_binary(upload_url: str, binary_path: Path) -> None:
    data = binary_path.read_bytes()
    req = request.Request(
        upload_url,
        data=data,
        method="PUT",
        headers={
            "Content-Type": "application/octet-stream",
            "Content-Length": str(len(data)),
        },
    )
    try:
        with request.urlopen(req, timeout=120) as _resp:
            return
    except error.HTTPError as exc:
        details = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"Upload failed: HTTP {exc.code}: {details}") from exc
    except error.URLError as exc:
        raise RuntimeError(f"Upload request failed: {exc}") from exc


def write_manifest(
    project_root: Path,
    version: str,
    board: str,
    channel: str,
    artifact_path: Path,
    artifact_size: int,
    artifact_sha256: str,
    create_response: Dict[str, Any],
    publish_response: Dict[str, Any],
) -> Path:
    out_dir = project_root / "build" / "ota-release-manifests"
    out_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    manifest_path = out_dir / f"ota_release_{version}_{timestamp}.json"

    manifest = {
        "timestamp_utc": timestamp,
        "version": version,
        "board": board,
        "channel": channel,
        "artifact": {
            "path": str(artifact_path),
            "size_bytes": artifact_size,
            "sha256": artifact_sha256,
        },
        "create_release_response": create_response,
        "publish_release_response": publish_response,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Build and publish OTA release")
    parser.add_argument("--api-base-url", required=True, help="OTA backend base URL")
    parser.add_argument("--admin-token", default=os.getenv("OTA_ADMIN_TOKEN", ""), help="Admin token for OTA release API")
    parser.add_argument("--version", default="", help="Release version (semver). If omitted, auto-detect.")
    parser.add_argument("--channel", default="stable", help="Release channel")
    parser.add_argument("--board", default="arduino_nano_33_ble", help="Target board")
    parser.add_argument("--build-dir", default="build_ota_release", help="Build directory")
    parser.add_argument("--notes", default="", help="Release notes")
    parser.add_argument("--artifact-path", default="", help="Use existing signed binary path instead of building")
    parser.add_argument("--sysbuild", action="store_true", default=True, help="Enable sysbuild")
    parser.add_argument("--pristine", action="store_true", default=True, help="Enable pristine build")
    parser.add_argument("--skip-build", action="store_true", help="Skip build and use existing artifact")
    parser.add_argument("--dry-run", action="store_true", help="Print actions without executing network/build")
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parents[1]
    api_base_url = normalize_base_url(args.api_base_url)
    build_dir = project_root / args.build_dir

    version = detect_version(project_root, args.version)
    print(f"[INFO] Version: {version}")

    version_conf = write_release_version_conf(project_root, version)
    print(f"[INFO] Version conf: {version_conf}")

    if args.dry_run:
        preview_build_dir = project_root / args.build_dir
        print("[DryRun] Planned actions:")
        if args.artifact_path.strip():
            print(f"  - Use existing artifact: {Path(args.artifact_path).resolve()}")
        else:
            print("  - Build release image")
            preview_cmd = resolve_west_cmd() + [
                "build",
                "-b",
                args.board,
                "-d",
                str(preview_build_dir),
            ]
            if args.sysbuild:
                preview_cmd.append("--sysbuild")
            if args.pristine:
                preview_cmd.append("--pristine")
            if args.sysbuild:
                preview_cmd.extend(
                    [
                        "--",
                        f"-DAutoWatering_EXTRA_CONF_FILE={version_conf}",
                        f"-Dapp_EXTRA_CONF_FILE={version_conf}",
                    ]
                )
            else:
                preview_cmd.extend(["--", f"-DEXTRA_CONF_FILE={version_conf}"])
            print("    [RUN] " + " ".join(preview_cmd))

        print(f"  - POST {api_base_url}/ota/releases")
        print("  - PUT  <upload_url from create-release response>")
        print(
            "  - POST "
            f"{api_base_url}/ota/releases/{version}/publish?channel={args.channel}&board={args.board}"
        )
        return 0

    if args.artifact_path.strip():
        signed_bin = Path(args.artifact_path).resolve()
        if not signed_bin.exists():
            raise RuntimeError(f"Provided --artifact-path not found: {signed_bin}")
    else:
        if not args.skip_build:
            build_release(
                project_root=project_root,
                build_dir=build_dir,
                board=args.board,
                sysbuild_enabled=args.sysbuild,
                pristine=args.pristine,
                extra_conf_file=version_conf,
            )
        signed_bin = find_signed_bin(build_dir)

    artifact_size = signed_bin.stat().st_size
    artifact_sha256 = sha256_of_file(signed_bin)
    artifact_name = signed_bin.name
    storage_key = f"ota/{args.channel}/{args.board}/{version}/{artifact_name}"

    print(f"[INFO] Artifact: {signed_bin}")
    print(f"[INFO] Size: {artifact_size} bytes")
    print(f"[INFO] SHA256: {artifact_sha256}")

    create_payload = {
        "version": version,
        "channel": args.channel,
        "board": args.board,
        "notes": args.notes,
        "artifact": {
            "name": artifact_name,
            "size_bytes": artifact_size,
            "sha256": artifact_sha256,
            "storage_key": storage_key,
        },
    }

    admin_token = args.admin_token.strip()
    if not admin_token:
        raise RuntimeError("Missing admin token. Use --admin-token or OTA_ADMIN_TOKEN env var.")

    headers = {"x-admin-token": admin_token}

    create_url = f"{api_base_url}/ota/releases"
    publish_url = (
        f"{api_base_url}/ota/releases/{version}/publish"
        f"?channel={args.channel}&board={args.board}"
    )

    create_response = api_json_request(create_url, "POST", headers, create_payload)
    if not create_response.get("ok"):
        raise RuntimeError(f"Create release failed: {create_response}")

    upload_url = str(create_response.get("upload_url", "")).strip()
    if not upload_url:
        raise RuntimeError(f"No upload_url returned by backend: {create_response}")

    print("[STEP] Uploading artifact...")
    upload_binary(upload_url, signed_bin)
    print("[OK] Artifact upload complete")

    publish_response = api_json_request(publish_url, "POST", headers, payload={})
    if not publish_response.get("ok"):
        raise RuntimeError(f"Publish release failed: {publish_response}")

    manifest_path = write_manifest(
        project_root=project_root,
        version=version,
        board=args.board,
        channel=args.channel,
        artifact_path=signed_bin,
        artifact_size=artifact_size,
        artifact_sha256=artifact_sha256,
        create_response=create_response,
        publish_response=publish_response,
    )

    print("[OK] OTA release published")
    print(f"[OK] Manifest: {manifest_path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"[ERROR] {exc}")
        raise SystemExit(1)
